#!/usr/bin/env python3
"""The UI <-> host protocol: protocol/methods.json is the one list of methods and events.

    python3 tools/protocol.py gen     write the generated Go, Rust and Kotlin tables
    python3 tools/protocol.py check   fail when a table is stale or an implementation disagrees

Owners:
    go    answered by fk-core (core/fk/core_method.go); the Kotlin host forwards it unchanged
    host  answered by the platform host (Android: BoxBridge, bridge/SlintHost.kt)
    ui    a platform UI service (menus, dialogs, IME, clipboard; Android: BoxActivity, NativeUi)

The top-level "version" is the protocol version every generated binding carries
(Go ProtocolVersion, Rust PROTOCOL_VERSION, Kotlin ProtocolGen.VERSION); "minClient" is
the oldest client protocol version the core still accepts. The "hello" method checks
them once at start-up. Bump "version" when a method or event changes incompatibly.

"capabilities" names the platform features a client may declare in hello (vpn_service,
file_picker, ...). The core keeps the declared names it knows and answers that effective
set; the Rust UI shows a platform feature only when app::has("<name>") is true. The
platform layer (ui/src/platform/) is the only place that lists them per client.

Targets say where a method belongs once the restructure is done: core (moves to Go),
android (stays in the Android shell), ui (stays in the platform UI layer).
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SPEC = ROOT / "protocol" / "methods.json"
GO_FK_OUT = ROOT / "core" / "fk" / "core_protocol_gen.go"
RS_OUT = ROOT / "ui" / "src" / "protocol_gen.rs"
KT_OUT = ROOT / "clients/android/app/src/main/java/io/nekohasekai/sfa/bridge/ProtocolGen.kt"
KT_DISPATCH = ROOT / "clients/android/app/src/main/java/io/nekohasekai/sfa/bridge/SlintHost.kt"
KT_ACTIVITY = ROOT / "clients/android/app/src/main/java/io/nekohasekai/sfa/bridge/BoxActivity.kt"
KT_SOURCES = ROOT / "clients/android/app/src/main/java"
GO_METHODS = ROOT / "core" / "fk" / "core_method.go"
GO_SOURCES = ROOT / "core" / "fk"
RUST_SOURCES = ROOT / "ui" / "src"
RUST_PLATFORM = RUST_SOURCES / "platform"
RUST_ANDROID_PLATFORM = RUST_PLATFORM / "android" / "mod.rs"
CAPABILITY = re.compile(r"^[a-z][a-z_]*[a-z]$")

OWNERS = {"go", "host", "ui"}
TARGETS = {"core", "android", "ui"}
NAME = re.compile(r"^[a-z][A-Za-z]*(\.[a-z][A-Za-z]*)?$")
HEADER = "Code generated by tools/protocol.py from protocol/methods.json. DO NOT EDIT."


def load():
    spec = json.loads(SPEC.read_text(encoding="utf-8"))
    errors = []
    for key in ("version", "minClient"):
        if type(spec.get(key)) is not int or spec[key] < 1:
            errors.append(f"{key} must be a positive integer")
    if not errors and spec["minClient"] > spec["version"]:
        errors.append("minClient must not be above version")
    capabilities = set()
    for entry in spec.get("capabilities", []):
        name = entry.get("name", "")
        if not CAPABILITY.match(name):
            errors.append(f"capabilities: bad name {name!r}")
        if name in capabilities:
            errors.append(f"capabilities: duplicate {name}")
        if not entry.get("description"):
            errors.append(f"capabilities {name}: needs a description")
        capabilities.add(name)
    seen = set()
    for kind in ("methods", "events"):
        for entry in spec[kind]:
            name = entry["name"]
            if not NAME.match(name):
                errors.append(f"{kind}: bad name {name!r}")
            if (kind, name) in seen:
                errors.append(f"{kind}: duplicate {name}")
            seen.add((kind, name))
            if entry.get("owner") not in OWNERS:
                errors.append(f"{kind} {name}: owner must be one of {sorted(OWNERS)}")
            if kind == "methods" and entry.get("target") not in TARGETS:
                errors.append(f"methods {name}: target must be one of {sorted(TARGETS)}")
            if kind == "methods" and entry.get("owner") == "go" and entry.get("target") != "core":
                errors.append(f"methods {name}: only target core can be owned by go")
    return spec, errors


def capability_names(spec):
    return [e["name"] for e in spec.get("capabilities", [])]


def names(spec, kind, owner=None):
    return sorted(e["name"] for e in spec[kind] if owner is None or e["owner"] == owner)


def render_go(spec):
    lines = [f"// {HEADER}", "", "package libbox", "",
             "// ProtocolVersion is the UI protocol version this core speaks (protocol/methods.json).",
             f"const ProtocolVersion = {spec['version']}", "",
             "// ProtocolMinClient is the oldest client protocol version this core accepts.",
             f"const ProtocolMinClient = {spec['minClient']}", "",
             "// uiProtocolMethods maps every protocol method to its owner.",
             "var uiProtocolMethods = map[string]string{"]
    lines += [f'\t"{e["name"]}": "{e["owner"]}",' for e in spec["methods"]]
    lines += ["}", "", "// uiProtocolCapabilities lists every capability a client may declare in hello.",
              "var uiProtocolCapabilities = map[string]struct{}{"]
    lines += [f'\t"{name}": {{}},' for name in capability_names(spec)]
    lines += ["}", "", "// uiProtocolEvents lists every protocol event.", "var uiProtocolEvents = map[string]struct{}{"]
    lines += [f'\t"{e["name"]}": {{}},' for e in spec["events"]]
    lines += ["}", ""]
    return "\n".join(lines)


def kt_set(values):
    if not values:
        return "emptySet()"
    return "setOf(\n" + "".join(f'        "{v}",\n' for v in values) + "    )"


def render_kt(spec):
    return "\n".join([
        f"// {HEADER}",
        "package io.nekohasekai.sfa.bridge",
        "",
        "/** The UI protocol's methods by owner (protocol/methods.json). */",
        "internal object ProtocolGen {",
        "    /** The UI protocol version (protocol/methods.json \"version\"). */",
        f"    const val VERSION: Int = {spec['version']}",
        "",
        "    /** The oldest client protocol version the core accepts. */",
        f"    const val MIN_CLIENT: Int = {spec['minClient']}",
        "",
        "    /** Answered by fk-core ([io.nekohasekai.sfa.fkcore.FkLib.uiInvoke]); the host only forwards them. */",
        f"    val GO_METHODS: Set<String> = {kt_set(names(spec, 'methods', 'go'))}",
        "",
        "    /** Answered by BoxBridge (hostDispatch in SlintHost.kt). */",
        f"    val HOST_METHODS: Set<String> = {kt_set(names(spec, 'methods', 'host'))}",
        "",
        "    /** Platform UI services answered by BoxActivity. */",
        f"    val UI_METHODS: Set<String> = {kt_set(names(spec, 'methods', 'ui'))}",
        "}",
        "",
    ])


def render_rs(spec):
    return "\n".join([
        f"// {HEADER}",
        "//! The UI protocol version (protocol/methods.json); the hello handshake sends it.",
        "",
        "/// The protocol version this UI speaks.",
        f"pub const PROTOCOL_VERSION: i64 = {spec['version']};",
        "",
        "/// The oldest client protocol version the core accepts.",
        "#[allow(dead_code)]",
        f"pub const PROTOCOL_MIN_CLIENT: i64 = {spec['minClient']};",
        "",
    ])


def gofmt_map_values(text):
    """Align the values of consecutive "key": value lines the way gofmt does."""
    lines = text.split("\n")
    out, block = [], []
    pattern = re.compile(r'^(\t+)("[^"]*"):\s*(.*)$')

    def flush():
        if block:
            width = max(len(m.group(2)) for m in block)
            for m in block:
                out.append(f"{m.group(1)}{m.group(2)}:{' ' * (width - len(m.group(2)) + 1)}{m.group(3)}")
            block.clear()

    for line in lines:
        m = pattern.match(line)
        if m:
            if block and block[0].group(1) != m.group(1):
                flush()
            block.append(m)
        else:
            flush()
            out.append(line)
    flush()
    return "\n".join(out)


def render_go_fk(spec):
    """The same table for fk-core's package fk (core/fk), gofmt-clean."""
    return gofmt_map_values(render_go(spec).replace("package libbox", "package fk", 1))


def outputs(spec):
    return {GO_FK_OUT: render_go_fk(spec), RS_OUT: render_rs(spec), KT_OUT: render_kt(spec)}


VERSION_PATTERNS = {
    GO_FK_OUT: r"^const ProtocolVersion = (\d+)$",
    RS_OUT: r"^pub const PROTOCOL_VERSION: i64 = (\d+);$",
    KT_OUT: r"^\s*const val VERSION: Int = (\d+)$",
}


def binding_versions():
    """The protocol version each generated binding on disk carries (None when absent)."""
    found = {}
    for path, pattern in VERSION_PATTERNS.items():
        match = re.search(pattern, path.read_text(encoding="utf-8"), re.M) if path.exists() else None
        found[path] = int(match.group(1)) if match else None
    return found


def kotlin_dispatch():
    text = KT_DISPATCH.read_text(encoding="utf-8")
    body = text[text.index("fun BoxBridge.hostDispatch"):]
    body = body[: body.index('else -> error("Unknown method')]
    return set(re.findall(r'^\s*"([A-Za-z.]+)" ->', body, re.M))


def kotlin_activity():
    text = KT_ACTIVITY.read_text(encoding="utf-8")
    found = set(re.findall(r'method == "([A-Za-z]+)"', text))
    call = text[text.index("fun slintCall"):]
    for labels in re.findall(r'^\s*((?:"[A-Za-z]+",?\s*)+)-> \{', call, re.M):
        found |= set(re.findall(r'"([A-Za-z]+)"', labels))
    native = re.search(r"NATIVE_UI = setOf\(([^)]*)\)", text)
    if native:
        found |= set(re.findall(r'"([A-Za-z]+)"', native.group(1)))
    if 'method.startsWith("ime")' in text:
        found.add("ime*")
    return found


def go_handlers():
    text = GO_METHODS.read_text(encoding="utf-8")
    table = text[text.index("var uiMethods = map[string]uiMethodHandler{"):]
    table = table[: table.index("\n}\n")]
    return set(re.findall(r'^\s*"([A-Za-z.]+)":', table, re.M))


def go_events():
    found = set()
    for path in sorted(p for p in GO_SOURCES.glob("*.go") if not p.name.endswith("_test.go")):
        found |= set(re.findall(r'uiEmit\("([A-Za-z]+)"', path.read_text(encoding="utf-8")))
    return found


def kotlin_events():
    found = set()
    for path in KT_SOURCES.rglob("*.kt"):
        text = path.read_text(encoding="utf-8")
        found |= set(re.findall(r'\bemit\("([A-Za-z]+)"', text))
        found |= set(re.findall(r'mapOf\("type" to "([A-Za-z]+)"', text))
    return found


def rust_references(methods):
    """Method names the Rust UI passes as string literals. Calls whose name is held in a
    variable are only caught when the literal still appears somewhere in the source."""
    known = set(methods)
    dotted = {m.split(".")[0] for m in methods if "." in m}
    found = set()
    for path in RUST_SOURCES.rglob("*.rs"):
        if path.name in ("shot.rs",) or path.name.endswith("_tests.rs"):
            continue
        for literal in re.findall(r'"([A-Za-z]+(?:\.[A-Za-z]+)?)"', path.read_text(encoding="utf-8")):
            if literal in known or ("." in literal and literal.split(".")[0] in dotted):
                found.add(literal)
    return found


def platform_capabilities():
    """The CAPABILITIES list of each platform file under ui/src/platform/."""
    found = {}
    for path in sorted(RUST_PLATFORM.rglob("*.rs")):
        text = path.read_text(encoding="utf-8")
        for match in re.finditer(r"CAPABILITIES: &\[&str\] = &\[([^\]]*)\]", text):
            found.setdefault(path, []).append(re.findall(r'"([a-z_]+)"', match.group(1)))
    return found


def rust_gates():
    """Capabilities the Rust UI tests with app::has("...") (or has("...") inside app.rs)."""
    found = set()
    for path in RUST_SOURCES.rglob("*.rs"):
        if path.name == "shot.rs" or path.name.endswith("_tests.rs"):
            continue
        found |= set(re.findall(r'\bhas\("([A-Za-z_]+)"\)', path.read_text(encoding="utf-8")))
    return found


def check(spec):
    errors = []
    for path, content in outputs(spec).items():
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            errors.append(f"{path.relative_to(ROOT)} is stale: run python3 tools/protocol.py gen")
    for path, version in binding_versions().items():
        if version != spec["version"]:
            errors.append(f"{path.relative_to(ROOT)} carries protocol version {version}, methods.json says {spec['version']}")
    methods = names(spec, "methods")

    dispatch = kotlin_dispatch()
    host = set(names(spec, "methods", "host"))
    go = set(names(spec, "methods", "go"))
    for m in sorted(host - dispatch):
        errors.append(f"host method {m} has no branch in SlintHost.hostDispatch")
    for m in sorted(dispatch - host):
        errors.append(f"SlintHost.hostDispatch handles {m}, which the protocol does not give to the host")

    handlers = go_handlers()
    for m in sorted(go - handlers):
        errors.append(f"go method {m} has no handler in core/fk/core_method.go")
    for m in sorted(handlers - go):
        errors.append(f"core/fk/core_method.go handles {m}, which the protocol does not give to go")

    activity = kotlin_activity()
    ui = set(names(spec, "methods", "ui"))
    for m in sorted(ui):
        if m not in activity and not (m.startswith("ime") and "ime*" in activity):
            errors.append(f"ui method {m} is not handled by BoxActivity.slintCall")
    for m in sorted(activity - ui - {"ime*"}):
        errors.append(f"BoxActivity.slintCall handles {m}, which the protocol does not give to ui")

    events = set(names(spec, "events"))
    host_events = set(names(spec, "events", "host")) | set(names(spec, "events", "ui"))
    for e in sorted(kotlin_events() - events):
        errors.append(f"Kotlin emits event {e}, which the protocol does not list")
    for e in sorted(go_events() - events):
        errors.append(f"libbox emits event {e}, which the protocol does not list")
    for e in sorted(host_events - kotlin_events()):
        errors.append(f"event {e} is listed for the host but nothing in Kotlin emits it")

    for m in sorted(rust_references(methods) - set(methods)):
        errors.append(f"ui/ calls {m}, which the protocol does not list")

    capabilities = set(capability_names(spec))
    declared = platform_capabilities()
    for path, lists in declared.items():
        for values in lists:
            for c in sorted(set(values) - capabilities):
                errors.append(f"{path.relative_to(ROOT)} declares capability {c}, which the protocol does not list")
    android = declared.get(RUST_ANDROID_PLATFORM)
    if not android:
        errors.append(f"{RUST_ANDROID_PLATFORM.relative_to(ROOT)} has no CAPABILITIES list")
    elif set(android[0]) != capabilities:
        errors.append(f"Android must declare every capability it has today; missing {sorted(capabilities - set(android[0]))}")
    gates = rust_gates()
    for c in sorted(gates - capabilities):
        errors.append(f"ui/ gates on capability {c}, which the protocol does not list")
    for c in sorted(capabilities - gates):
        errors.append(f"capability {c} gates nothing in ui/ (no app::has(\"{c}\"))")
    return errors


def main():
    if len(sys.argv) != 2 or sys.argv[1] not in ("gen", "check"):
        print(__doc__)
        return 2
    spec, errors = load()
    if errors:
        print("\n".join(errors))
        return 1
    if sys.argv[1] == "gen":
        for path, content in outputs(spec).items():
            path.write_text(content, encoding="utf-8")
        return 0
    errors = check(spec)
    if errors:
        print("\n".join(errors))
        return 1
    counts = {o: len(names(spec, "methods", o)) for o in sorted(OWNERS)}
    print(f"protocol ok: version {spec['version']} (min client {spec['minClient']}), {len(capability_names(spec))} capabilities, {len(names(spec, 'methods'))} methods {counts}, {len(names(spec, 'events'))} events")
    return 0


if __name__ == "__main__":
    sys.exit(main())
