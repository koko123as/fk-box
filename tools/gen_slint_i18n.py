"""Generates ui-slint/i18n/zh/LC_MESSAGES/fkui.po from the Compose UI's
Simplified Chinese strings (compose/BoxStrings.kt, keys are the English source
text) plus the few strings only the Slint UI uses (EXTRA below).

The Slint pages use @tr("English") with no translation context and the Rust
side reads the same file (ui-slint/src/i18n.rs), so both translate exactly as
the Compose tr() did. Run from the repository root after changing BoxStrings.kt.
"""
import re
from pathlib import Path

SOURCE = Path('app/src/main/java/io/nekohasekai/sfa/compose/BoxStrings.kt')
TARGET = Path('ui-slint/i18n/zh/LC_MESSAGES/fkui.po')

EXTRA = {
    'Not available in the Slint UI yet': 'Slint 界面暂未提供此页面',
    'This page has not been ported to the Rust + Slint UI. Its Compose version remains in the source tree; see slint-manifest.md.':
        '此页面尚未移植到 Rust + Slint 界面，Compose 版本仍保留在源码中，详见 slint-manifest.md。',
    'Move up': '上移',
    'Move down': '下移',
    'Add': '添加',
    'Remove': '移除',
}


def unescape(value: str) -> str:
    return re.sub(r'\\(.)', lambda m: {'n': '\n', 't': '\t'}.get(m.group(1), m.group(1)), value)


def po(value: str) -> str:
    return '"' + value.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n').replace('\t', '\\t') + '"'


def main():
    text = SOURCE.read_text()
    pairs = {}
    for key, value in re.findall(r'map\["((?:\\.|[^"\\])*)"\]\s*=\s*"((?:\\.|[^"\\])*)"', text):
        pairs[unescape(key)] = unescape(value)
    for key, value in EXTRA.items():
        pairs.setdefault(key, value)
    lines = ['# Generated by tools/gen_slint_i18n.py from compose/BoxStrings.kt. Do not edit.',
             'msgid ""', 'msgstr ""', '"Content-Type: text/plain; charset=UTF-8\\n"', '"Language: zh\\n"', '']
    for key in sorted(pairs):
        lines += [f'msgid {po(key)}', f'msgstr {po(pairs[key])}', '']
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text('\n'.join(lines))
    print(f'{len(pairs)} strings -> {TARGET}')


if __name__ == '__main__':
    main()
